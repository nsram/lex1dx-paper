"""Regenerate fixtures/expected_cpp.txt from the C++ lex_cli: one line per (data, k, weights, preset).

    python fixtures/make_expected.py path/to/lex_cli      # e.g. build/lex_cli or build/Release/lex_cli.exe

Run fixtures/gen_fixtures.py first. The Python tests check that the file is current.
"""
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PRESETS = ("hybrid", "plain", "deck", "exact")


def main(cli):
    data = os.path.join(HERE, "data")
    out = ["# data|k|weights|preset|key=value...  (generated by make_expected.py from lex_cli)"]
    with open(os.path.join(HERE, "cases.txt"), encoding="ascii") as f:
        cases = [line.split() for line in f if line.strip() and not line.startswith("#")]
    for name, k, w in cases:
        for preset in PRESETS:
            args = [cli, os.path.join(data, name + ".txt"), k, "--preset", preset]
            if w != "-":
                args += ["--weights", os.path.join(data, w + ".txt")]
            run = subprocess.run(args, capture_output=True, text=True)  # status 1 = error= line, kept
            out.append("|".join([name, k, w, preset] + run.stdout.splitlines()))
    with open(os.path.join(HERE, "expected_cpp.txt"), "w", newline="\n", encoding="ascii") as f:
        f.write("\n".join(out) + "\n")
    print(f"wrote expected_cpp.txt ({len(out) - 1} lines)")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
